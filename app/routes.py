@bp.route('/recipe/<recipe_id>', methods=['GET'])
# @jwt_required
def get_recipe_details(recipe_id):
    """Fetches the full details for a single recipe from the database."""
    try:
        response = supabase.table("recipes").select("full_recipe_data").eq("id", recipe_id).single().execute()

        if not response.data:
            return jsonify({"error": "Recipe not found."}), 404

        full_recipe = response.data.get('full_recipe_data')
        return jsonify(full_recipe)

    except Exception as e:
        print(f"Error fetching recipe details: {e}")
        return jsonify({"error": "Could not retrieve recipe details.", "details": str(e)}), 500

@bp.route('/recipe/<recipe_id>/favorite', methods=['POST'])
@jwt_required
def toggle_favorite(recipe_id):
    user_id = request.user.id  # uuid string

    try:
        # Call the RPC. Adjust if your supabase client uses different method signature.
        rpc_resp = supabase.rpc('toggle_favorite', {'p_user': user_id, 'p_recipe': recipe_id}).execute()

        # Inspect supabase wrapper safely
        status = getattr(rpc_resp, "status_code", None)
        data = getattr(rpc_resp, "data", None)

        # If RPC returned HTTP error
        if isinstance(status, int) and status >= 400:
            return jsonify({"error": "RPC call failed", "details": data}), 500

        # Normalize response (supabase sometimes returns a list with one object)
        result = None
        if isinstance(data, list) and len(data) == 1:
            result = data[0]
        else:
            result = data

        if not result:
            # Unexpected empty response
            return jsonify({"error": "Empty response from RPC", "raw": rpc_resp.__dict__}), 500

        # Return the JSON result from the database function (status, is_favorited, recipe)
        return jsonify({"ok": True, "result": result})

    except Exception as e:
        print("toggle_favorite error:", e)
        return jsonify({"error": "Server exception", "details": str(e)}), 500

# --- Get all recipe generation history for a user ---
@bp.route('/history', methods=['GET'])
@jwt_required
def get_user_history():
    """
    Fetches all recipes ever generated by the logged-in user,
    formatted to match the recipe-list component structure.
    """
    user_id = request.user.id
    
    try:
        # Step 1: Get all generation history IDs for the current user
        # history_response = supabase.table("generation_history").select("id").eq("user_id", user_id).execute()
        history_response = supabase.table("generation_history").select("id").eq("user_id", user_id).execute()

        if not history_response.data:
            # If the user has no generation history, return an empty list
            return jsonify({"recipes": []})

        generation_ids = [item['id'] for item in history_response.data]

        # Step 2: Fetch all recipes linked to those generation IDs, ordered by creation date
        recipes_response = supabase.table("recipes") \
            .select("id, title, image_url, cook_time, difficulty") \
            .in_("generation_id", generation_ids) \
            .order("created_at", desc=True) \
            .execute()

        if not recipes_response.data:
            return jsonify({"recipes": []})

        # Step 3: Format the data to match the structure required by recipe-list.jsx
        formatted_recipes = []
        for recipe in recipes_response.data:
            formatted_recipes.append({
                "id": recipe.get("id"),
                "title": recipe.get("title"),
                "imageUrl": recipe.get("image_url"),
                "cookTime": recipe.get("cook_time"),
                "difficulty": recipe.get("difficulty")
            })
        return jsonify({"recipes": formatted_recipes})

    except Exception as e:
        print(f"Error fetching user history: {e}")
        return jsonify({"error": "Could not retrieve user history.", "details": str(e)}), 500

